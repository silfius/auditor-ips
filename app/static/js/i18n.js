  const DEFAULT_TIME_ZONE = 'Europe/Madrid';

  let _active = 'es';

  window.t = function(key, fallback, vars) {
    let value = (_DICTS[_active] && _DICTS[_active][key] !== undefined)
      ? _DICTS[_active][key]
      : ((_DICTS.es && _DICTS.es[key]) || fallback || key);
    if (value === key && fallback) value = fallback;
    if (vars && typeof value === 'string') {
      value = value.replace(/\{([^}]+)\}/g, (_, name) => {
        const v = vars[name];
        return v === undefined || v === null ? '' : String(v);
      });
    }
    return value;
  };

  window.getLang = function() { return _active; };

  function _localeFromLang(lang) {
    const v = String(lang || _active || 'es').toLowerCase();
    if (v === 'en') return 'en-GB';
    if (v === 'ca') return 'ca-ES';
    return 'es-ES';
  }

  function _safeTimeZone() {
    return localStorage.getItem('auditor_app_tz') || DEFAULT_TIME_ZONE;
  }

  window.getDefaultTimeZone = function() { return DEFAULT_TIME_ZONE; };
  window.getLocale = function() { return _localeFromLang(_active); };
  window.getTimeZone = function() { return _safeTimeZone(); };

  window.fmtNumber = function(value, extra) {
    const n = Number(value);
    if (!Number.isFinite(n)) return '—';
    try {
      return new Intl.NumberFormat(_localeFromLang(_active), extra || {}).format(n);
    } catch (_) {
      return String(n);
    }
  };

  window.setTimeZone = function(tz) {
    const next = String(tz || DEFAULT_TIME_ZONE).trim() || DEFAULT_TIME_ZONE;
    localStorage.setItem('auditor_app_tz', next);
    document.dispatchEvent(new CustomEvent('timezonechange', { detail: next }));
    return next;
  };

  window.fmtTime = function(value, extra) {
    if (!value) return '—';
    try {
      const d = new Date(value);
      if (isNaN(d.getTime())) return '—';
      return new Intl.DateTimeFormat(_localeFromLang(_active), Object.assign({
        timeZone: _safeTimeZone(),
        hour: '2-digit',
        minute: '2-digit'
      }, extra || {})).format(d);
    } catch (_) { return '—'; }
  };

  window.fmtDate = function(value, extra) {
    if (!value) return '—';
    try {
      const d = new Date(value);
      if (isNaN(d.getTime())) return '—';
      return new Intl.DateTimeFormat(_localeFromLang(_active), Object.assign({
        timeZone: _safeTimeZone(),
        day: '2-digit',
        month: '2-digit'
      }, extra || {})).format(d);
    } catch (_) { return '—'; }
  };

  window.fmtDateTime = function(value, extra) {
    if (!value) return '—';
    try {
      const d = new Date(value);
      if (isNaN(d.getTime())) return '—';
      return new Intl.DateTimeFormat(_localeFromLang(_active), Object.assign({
        timeZone: _safeTimeZone(),
        day: '2-digit',
        month: '2-digit',
        hour: '2-digit',
        minute: '2-digit'
      }, extra || {})).format(d);
    } catch (_) { return '—'; }
  };

  window.setLang = async function(lang) {
    if (!_DICTS[lang]) return;
    _active = lang;
    localStorage.setItem('auditor_lang', lang);
    document.documentElement.lang = lang;
    _applyDOM();
    try {
      await fetch('/api/settings', {
        method: 'PUT',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ ui_lang: lang }),
      });
    } catch(_) {}
    document.dispatchEvent(new CustomEvent('langchange', { detail: lang }));
  };

  window.applyI18n = function(root) {
    (root || document).querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      const attr = el.getAttribute('data-i18n-attr');
      const val = window.t(key);
      if (attr) { el.setAttribute(attr, val); }
      else {
        // Actualiza solo el TextNode, preservando iconos/badges hijos
        for (const node of el.childNodes) {
          if (node.nodeType === Node.TEXT_NODE && node.textContent.trim()) {
            node.textContent = val; return;
          }
        }
        el.appendChild(document.createTextNode(val));
      }
    });
  };

  // Llamado desde config.js tras cargar settings desde BD
  window._i18nApplyFromSettings = function(lang) {
    if (lang && _DICTS[lang]) {
      _active = lang;
      localStorage.setItem('auditor_lang', lang);
      document.documentElement.lang = lang;
      _applyDOM();
    }
  };

  function _applyDOM() {
    window.applyI18n(document);
    const sel = document.getElementById('cfgLangSelect');
    if (sel) sel.value = _active;
  }

  function _init() {
    const saved = localStorage.getItem('auditor_lang');
    if (saved && _DICTS[saved]) _active = saved;
    document.documentElement.lang = _active;
    _applyDOM();
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', _init);
  } else {
    _init();
  }

