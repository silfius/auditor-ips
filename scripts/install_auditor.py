    profile = args.profile
    if not args.yes and not args.profile_explicit:
        section("Tipo de instalación", "El perfil recomendado evita preguntas técnicas que pueden detectarse con seguridad.")
        profile = choose(
            "Perfil",
            [
                ("recommended", "Recomendado: red, IP, puerto y almacenamiento guiados"),
                ("advanced", "Avanzado: revisar identidad, DNS, cookie y TLS"),
            ],
            0,
            False,
        )

    selected = choose_interface(args, args.yes)
    detected_ip = selected.ip if selected else ""
    detected_network = selected.network if selected else "192.168.1.0/24"
    selected_interface = selected.interface if selected else ""

    section("Acceso HTTPS", "El puerto debe estar libre porque Auditor IPs utiliza la red del host.")
    default_port = args.port or existing.get("PORT") or DEFAULT_PORT
    while True:
        port_raw = ask("Puerto HTTPS", default_port, args.yes)
        port = validate_port(port_raw)
        if port_is_free(port) or (target_dir / ".env").exists():
            break
        suggested = find_free_port(port + 1)
        if args.yes:
            port = suggested
            note(f"Puerto solicitado ocupado; se utilizará {suggested}.")
            break
        warn(f"El puerto {port} está ocupado. Puerto libre sugerido: {suggested}.")
        default_port = str(suggested)

    default_container = args.container_name or DEFAULT_CONTAINER_NAME
    if profile == "advanced":
        container_name = sanitize_container_name(ask("Nombre del contenedor", default_container, args.yes))
    else:
        container_name = sanitize_container_name(default_container)
        note(f"Contenedor generado: {container_name}")
    if container_exists(container_name) and not (target_dir / ".env").exists():
        raise RuntimeError(f"Ya existe un contenedor llamado {container_name}.")

    instance_id = sanitize_instance_id(args.instance_id or existing.get("AUDITOR_INSTANCE_ID", "")) or generate_instance_id(container_name)
