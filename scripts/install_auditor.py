def wait_health(target_dir: Path, port: str, attempts: int = 60) -> None:
    url = f"https://127.0.0.1:{port}/api/system/healthz"
    for attempt in range(1, attempts + 1):
        result = run_cmd(["curl", "-kfsS", "--connect-timeout", "2", "--max-time", "8", url], capture=True)
        if result.returncode == 0:
            log(color(f"healthz OK en intento {attempt}", "ok"))
            return
        time.sleep(2)
    ps = run_cmd(docker_cmd("compose", "ps", "-a"), cwd=target_dir, capture=True)
    logs = run_cmd(docker_cmd("compose", "logs", "--no-color", "--tail", "160"), cwd=target_dir, capture=True)
    raise RuntimeError(f"healthz no respondió en {url}.\n\nEstado:\n{ps.stdout}{ps.stderr}\nLogs:\n{logs.stdout}{logs.stderr}")


def validate_tls(target_dir: Path, port: str, expected_ip: str, expected_dns: str) -> None:
    server_name = expected_dns.split(",", 1)[0].strip() if expected_dns else "localhost"
    client = subprocess.run(
        ["openssl", "s_client", "-connect", f"127.0.0.1:{port}", "-servername", server_name],
        input="",
        text=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        cwd=str(target_dir),
    )
    if client.returncode != 0 or "BEGIN CERTIFICATE" not in client.stdout:
        raise RuntimeError("No se pudo obtener el certificado TLS servido.")
    cert = subprocess.run(
        ["openssl", "x509", "-noout", "-ext", "subjectAltName"],
        input=client.stdout,
        text=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
    )
    if cert.returncode != 0:
        raise RuntimeError("No se pudo leer subjectAltName del certificado TLS.")
    expected = {"IP Address:127.0.0.1", "DNS:localhost"}
    if expected_ip:
        expected.add(f"IP Address:{expected_ip}")
    if expected_dns:
        expected.update(
            f"DNS:{item.strip()}"
            for item in expected_dns.split(",")
            if item.strip()
        )
    actual = set(
        re.findall(r"(?:DNS:[^,\s]+|IP Address:[^,\s]+)", cert.stdout)
    )
    missing = sorted(expected - actual)
    unexpected = sorted(actual - expected)
    if missing or unexpected:
        details = []
        if missing:
            details.append("faltan " + ", ".join(missing))
        if unexpected:
            details.append("sobran " + ", ".join(unexpected))
        raise RuntimeError(
            "El conjunto SAN del certificado no coincide exactamente: "
            + "; ".join(details)
        )
    log(color("Certificado TLS y conjunto SAN exacto: OK", "ok"))

def build_and_start(target_dir: Path, no_start: bool, port: str, tls_ip: str = "", tls_dns: str = "") -> None:
    log("Construyendo imagen Docker...")
    run_cmd(docker_cmd("compose", "build"), cwd=target_dir, check=True, capture=False)
    if no_start:
        note("Arranque omitido por --no-start.")
        return
    log("Arrancando Auditor IPs...")
    run_cmd(docker_cmd("compose", "up", "-d"), cwd=target_dir, check=True, capture=False)
    wait_health(target_dir, port)
    validate_tls(target_dir, port, tls_ip, tls_dns)


