def log(message: str = "") -> None:
    print(message, flush=True)


USE_COLOR = sys.stdout.isatty() and not os.environ.get("NO_COLOR")
ANSI = {
    "reset": "\033[0m",
    "title": "\033[1;36m",
    "muted": "\033[2m",
    "info": "\033[36m",
    "ok": "\033[32m",
    "warn": "\033[33m",
    "error": "\033[31m",
    "prompt": "\033[1m",
}


def color(text: str, name: str) -> str:
    if not USE_COLOR:
        return text
    return f"{ANSI.get(name, '')}{text}{ANSI['reset']}"


def section(title: str, description: str = "") -> None:
    log()
    log(color(f"== {title} ==", "title"))
    if description:
        log(color(f"  {description}", "info"))


def note(message: str) -> None:
    log(color(f"  - {message}", "muted"))


def warn(message: str) -> None:
    log(color(f"ADVERTENCIA: {message}", "warn"))


def run_cmd(
    cmd: list[str],
    cwd: Path | None = None,
    check: bool = False,
    capture: bool = True,
    timeout: int | None = None,
) -> CommandResult:
    proc = subprocess.run(
        cmd,
        cwd=str(cwd) if cwd else None,
        text=True,
        stdout=subprocess.PIPE if capture else None,
        stderr=subprocess.PIPE if capture else None,
        timeout=timeout,
    )
    result = CommandResult(proc.returncode, proc.stdout or "", proc.stderr or "")
    if check and result.returncode != 0:
        raise RuntimeError(
            "Comando fallido: "
            + " ".join(cmd)
            + f"\nSTDOUT:\n{result.stdout}\nSTDERR:\n{result.stderr}"
        )
    return result


def command_exists(name: str) -> bool:
    return shutil.which(name) is not None


def docker_prefix() -> list[str]:
    return ["sudo", "docker"] if os.getenv("AUDITOR_DOCKER_USE_SUDO") == "1" else ["docker"]


def docker_cmd(*args: str) -> list[str]:
    return docker_prefix() + list(args)


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def read_os_release() -> dict[str, str]:
    path = Path("/etc/os-release")
    values: dict[str, str] = {}
    if not path.exists():
        return values
    for raw in path.read_text(encoding="utf-8", errors="replace").splitlines():
        if "=" not in raw:
            continue
        key, value = raw.split("=", 1)
        values[key] = value.strip().strip('"')
    return values


def detect_linux_family() -> str:
    data = read_os_release()
    raw = " ".join((data.get("ID", ""), data.get("ID_LIKE", ""), data.get("NAME", ""))).lower()
    if any(token in raw for token in ("debian", "ubuntu", "linuxmint", "raspbian")):
        return "debian"
    if any(token in raw for token in ("arch", "manjaro", "endeavouros")):
        return "arch"
    return "unknown"


def validate_platform() -> list[str]:
    warnings: list[str] = []
    if platform.system().lower() != "linux":
        raise RuntimeError("El instalador del servidor solo soporta Linux.")
    arch = platform.machine().lower()
    if arch not in SUPPORTED_ARCHES:
        raise RuntimeError(f"Arquitectura no certificada: {arch}.")
    if detect_linux_family() == "unknown":
        warnings.append("Distribución no clasificada: las dependencias deben instalarse manualmente.")
    return warnings


def validate_commands() -> None:
    missing = [name for name in ("git", "python3", "curl", "openssl", "ip", "tar", "docker") if not command_exists(name)]
    if missing:
        raise RuntimeError("Faltan comandos requeridos: " + ", ".join(missing) + ". Ejecuta ./installers/linux/install.sh.")
    result = run_cmd(docker_cmd("compose", "version"), capture=True)
    if result.returncode != 0:
        raise RuntimeError("Docker Compose V2 no está disponible. Ejecuta ./installers/linux/install.sh --install-deps.")
    result = run_cmd(docker_cmd("info"), capture=True)
    if result.returncode != 0:
        raise RuntimeError("No se puede acceder al daemon Docker. Revisa permisos o el servicio Docker.")


def ask(prompt: str, default: str = "", assume_yes: bool = False, help_text: str = "") -> str:
    if assume_yes:
        return default
    if help_text:
        note(help_text)
    suffix = f" [{default}]" if default else ""
    value = input(color(f"{prompt}{suffix}: ", "prompt")).strip()
    return value or default


def ask_bool(prompt: str, default: bool, assume_yes: bool = False, help_text: str = "") -> bool:
    if assume_yes:
        return default
    if help_text:
        note(help_text)
    suffix = "S/n" if default else "s/N"
    value = input(color(f"{prompt} [{suffix}]: ", "prompt")).strip().lower()
    if not value:
        return default
    return value in {"s", "si", "sí", "y", "yes"}


def choose(prompt: str, options: list[tuple[str, str]], default_index: int, assume_yes: bool) -> str:
    if not options:
        raise RuntimeError("No hay opciones disponibles.")
    if assume_yes:
        return options[default_index][0]
    for index, (_, label) in enumerate(options, start=1):
        marker = " (recomendado)" if index - 1 == default_index else ""
        log(f"  {index}. {label}{marker}")
    while True:
        raw = input(color(f"{prompt} [{default_index + 1}]: ", "prompt")).strip()
        if not raw:
            return options[default_index][0]
        if raw.isdigit() and 1 <= int(raw) <= len(options):
            return options[int(raw) - 1][0]
        warn("Selecciona un número válido.")


def confirm(prompt: str, assume_yes: bool) -> bool:
    return ask_bool(prompt, False, assume_yes)


def sanitize_container_name(value: str) -> str:
    cleaned = re.sub(r"[^A-Za-z0-9_.-]+", "_", value.strip()).strip("._-")
    return cleaned[:128] or DEFAULT_CONTAINER_NAME


def sanitize_instance_id(value: str) -> str:
    cleaned = re.sub(r"[^A-Za-z0-9_.-]+", "_", (value or "").strip()).strip("._-")
    return cleaned[:64]


def generate_instance_id(container_name: str) -> str:
    return f"{sanitize_instance_id(container_name) or DEFAULT_CONTAINER_NAME}_{secrets.token_hex(4)}"


def cookie_name_from_instance(instance_id: str) -> str:
    suffix = re.sub(r"[^A-Za-z0-9_]+", "_", instance_id).strip("_")[:48] or secrets.token_hex(4)
    return f"auditor_session_{suffix}"


def is_probably_virtual_interface(name: str) -> bool:
    lowered = name.lower()
    return lowered.startswith(("lo", "docker", "br-", "veth", "virbr", "tun", "tap", "wg", "zt", "tailscale", "macvlan"))


def detect_default_interfaces() -> set[str]:
    result = run_cmd(["ip", "-j", "route", "show", "default"], capture=True)
    if result.returncode != 0:
        return set()
    try:
        rows = json.loads(result.stdout or "[]")
    except json.JSONDecodeError:
        return set()
    return {str(row.get("dev") or "") for row in rows if row.get("dev")}


def detect_ipv4_candidates(include_virtual: bool = True) -> list[InterfaceCandidate]:
    result = run_cmd(["ip", "-j", "-4", "addr", "show"], capture=True)
    if result.returncode != 0:
        return []
    try:
        rows = json.loads(result.stdout or "[]")
    except json.JSONDecodeError:
        return []
    default_ifaces = detect_default_interfaces()
    candidates: list[InterfaceCandidate] = []
    for row in rows:
        name = str(row.get("ifname") or "")
        if name == "lo":
            continue
        virtual = is_probably_virtual_interface(name)
        if virtual and not include_virtual:
            continue
        state = str(row.get("operstate") or "UNKNOWN")
        kind = str((row.get("linkinfo") or {}).get("info_kind") or "physical")
        for info in row.get("addr_info") or []:
            if info.get("family") != "inet" or info.get("scope") != "global":
                continue
            ip = str(info.get("local") or "")
            prefix = int(info.get("prefixlen") or 0)
            try:
                iface = ipaddress.ip_interface(f"{ip}/{prefix}")
            except ValueError:
                continue
            candidates.append(
                InterfaceCandidate(
                    interface=name,
                    ip=str(iface.ip),
                    cidr=str(iface),
                    network=str(iface.network),
                    default_route=name in default_ifaces,
                    virtual=virtual,
                    state=state,
                    kind=kind,
                )
            )
    candidates.sort(key=lambda item: (item.virtual, not item.default_route, item.interface, item.ip))
    return candidates


def choose_interface(args: argparse.Namespace, assume_yes: bool) -> InterfaceCandidate | None:
    candidates = detect_ipv4_candidates(include_virtual=True)
    if not candidates:
        warn("No se han detectado interfaces IPv4 globales.")
        return None
    section("Interfaz y red", "Selecciona la interfaz conectada a la red que quieres auditar.")
    options: list[tuple[str, str]] = []
    default_index = 0
    for index, item in enumerate(candidates):
        if item.default_route and not item.virtual:
            default_index = index
            break
    for item in candidates:
        flags = []
        if item.default_route:
            flags.append("ruta por defecto")
        if item.virtual:
            flags.append("virtual")
        flags.append(item.state.lower())
        options.append((item.interface + "|" + item.ip, f"{item.interface}: {item.ip} · red {item.network} · {', '.join(flags)}"))
    selected = choose("Interfaz", options, default_index, assume_yes)
    iface_name, ip = selected.split("|", 1)
    return next(item for item in candidates if item.interface == iface_name and item.ip == ip)


def validate_port(value: str) -> int:
    try:
        port = int(str(value).strip())
    except ValueError as exc:
        raise RuntimeError("El puerto debe ser numérico.") from exc
    if not 1 <= port <= 65535:
        raise RuntimeError("El puerto debe estar entre 1 y 65535.")
    return port


def port_is_free(port: int) -> bool:
    for family, address in ((socket.AF_INET, "0.0.0.0"), (socket.AF_INET6, "::")):
        try:
            with socket.socket(family, socket.SOCK_STREAM) as sock:
                sock.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
                sock.bind((address, port))
        except OSError:
            return False
    return True


def find_free_port(start: int) -> int:
    for port in range(max(1024, start), min(65535, start + 1000)):
        if port_is_free(port):
            return port
    raise RuntimeError("No se ha encontrado un puerto libre cercano.")


def validate_cidr(value: str) -> str:
    try:
        network = ipaddress.ip_network(value.strip(), strict=False)
    except ValueError as exc:
        raise RuntimeError(f"CIDR no válido: {value}") from exc
    if network.version != 4:
        raise RuntimeError("La red principal debe ser IPv4 en esta versión.")
    if network.num_addresses > 65536:
        raise RuntimeError("La red es demasiado grande. Usa una red /16 o más pequeña.")
    return str(network)


def validate_ip(value: str, allow_empty: bool = False) -> str:
    value = value.strip()
    if not value and allow_empty:
        return ""
    try:
        return str(ipaddress.ip_address(value))
    except ValueError as exc:
        raise RuntimeError(f"IP no válida: {value}") from exc


def validate_dns_name(value: str) -> str:
    value = value.strip().strip(".")
    if not value:
        return ""
    if len(value) > 253 or not re.fullmatch(r"[A-Za-z0-9](?:[A-Za-z0-9.-]*[A-Za-z0-9])?", value):
        raise RuntimeError(f"Nombre DNS no válido: {value}")
    return value


