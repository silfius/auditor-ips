def sqlite_backup(source: Path, destination: Path) -> None:
    if not source.exists():
        return
    destination.parent.mkdir(parents=True, exist_ok=True)
    source_conn = sqlite3.connect(f"file:{source}?mode=ro", uri=True, timeout=60)
    destination_conn = sqlite3.connect(destination, timeout=60)
    try:
        source_conn.backup(destination_conn)
        quick_check = destination_conn.execute("PRAGMA quick_check").fetchone()[0]
        if quick_check != "ok":
            raise RuntimeError(f"Backup SQLite inválido: {quick_check}")
    finally:
        destination_conn.close()
        source_conn.close()


def create_upgrade_backup(target_dir: Path, env_values: dict[str, str]) -> Path:
    stamp = datetime.now(timezone.utc).strftime("%Y%m%d-%H%M%S")
    backup_root = target_dir / "upgrade_backups" / stamp
    backup_root.mkdir(parents=True, exist_ok=False)
    for name in (".env", "docker-compose.yml", "install_state.json", "install_summary.md", "upgrade_state.json", "upgrade_summary.md"):
        source = target_dir / name
        if source.is_file():
            destination = backup_root / name
            destination.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(source, destination)
    data_dir = resolve_host_path(target_dir, env_values.get("DATA_DIR", "./data"))
    db_source = data_dir / "auditor.db"
    db_destination = backup_root / "data" / "auditor.db"
    sqlite_backup(db_source, db_destination)
    head = run_cmd(["git", "rev-parse", "HEAD"], cwd=target_dir, capture=True)
    manifest = {
        "created_at": datetime.now(timezone.utc).isoformat(),
        "previous_git_head": head.stdout.strip() if head.returncode == 0 else "",
        "source_db": str(db_source),
        "backup_db": str(db_destination) if db_destination.exists() else "",
        "files": [],
    }
    for path in sorted(backup_root.rglob("*")):
        if path.is_file():
            manifest["files"].append({"path": path.relative_to(backup_root).as_posix(), "bytes": path.stat().st_size, "sha256": sha256_file(path)})
    (backup_root / "manifest.json").write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    log(color(f"Backup de upgrade válido: {backup_root}", "ok"))
    return backup_root


def load_install_state(target_dir: Path) -> dict[str, object]:
    path = target_dir / "install_state.json"
    if not path.exists():
        return {}
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, OSError):
        return {}


def reconcile_env(target_dir: Path) -> dict[str, str]:
    env_path = target_dir / ".env"
    template_path = target_dir / "installers" / "linux" / "env.linux.example"
    if not template_path.exists():
        raise RuntimeError("La nueva versión no contiene installers/linux/env.linux.example.")
    existing = read_env_file(env_path)
    rendered = render_env(template_path.read_text(encoding="utf-8"), existing)
    env_path.write_text(rendered, encoding="utf-8")
    env_path.chmod(0o600)
    log(".env reconciliado: valores locales conservados y nuevas variables añadidas.")
    return read_env_file(env_path)


def reconcile_compose(target_dir: Path, env_values: dict[str, str], args: argparse.Namespace) -> None:
    compose_path = target_dir / "docker-compose.yml"
    template_path = target_dir / "installers" / "linux" / "docker-compose.linux.yml.example"
    if not template_path.exists():
        raise RuntimeError("La nueva versión no contiene installers/linux/docker-compose.linux.yml.example.")
    candidate = render_compose(template_path.read_text(encoding="utf-8"), env_values)
    current_hash = sha256_file(compose_path)
    state = load_install_state(target_dir)
    generated_hash = str(state.get("generated_compose_sha256") or "")
    manually_modified = bool(generated_hash and current_hash != generated_hash)
    if manually_modified:
        if args.yes:
            raise RuntimeError("docker-compose.yml contiene cambios manuales. Ejecuta el upgrade interactivo para decidir cómo reconciliarlos.")
        section("Compose modificado", "La definición local contiene cambios manuales.")
        action = choose("Acción", [("keep", "Conservar el Compose actual"), ("replace", "Regenerar desde la nueva plantilla"), ("cancel", "Cancelar upgrade")], 0, False)
        if action == "cancel":
            raise RuntimeError("Upgrade cancelado por cambios manuales en Compose.")
        if action == "keep":
            warn("Se conserva Compose actual. Revisa cambios de la nueva plantilla.")
            return
    compose_path.write_text(candidate, encoding="utf-8")
    log("docker-compose.yml reconciliado con la nueva plantilla.")


def run_upgrade(args: argparse.Namespace, target_dir: Path) -> int:
    section("Upgrade guiado", "Crea backup consistente, actualiza código y revierte si falla la validación.")
    if not (target_dir / ".git").exists() or not (target_dir / ".env").exists() or not (target_dir / "docker-compose.yml").exists():
        raise RuntimeError("--upgrade requiere una instalación Git con .env y docker-compose.yml.")
    env_values = read_env_file(target_dir / ".env")
    port = env_values.get("PORT", DEFAULT_PORT)
    if not args.yes and not confirm("Continuar con el upgrade", False):
        return 1
    backup_dir = create_upgrade_backup(target_dir, env_values)
    previous_head = run_cmd(["git", "rev-parse", "HEAD"], cwd=target_dir, check=True).stdout.strip()
    try:
        clone_or_update_repo(args.repo_url, args.branch, target_dir, args.dry_run)
        if args.dry_run:
            return 0
        env_values = reconcile_env(target_dir)
        port = env_values.get("PORT", DEFAULT_PORT)
        reconcile_compose(target_dir, env_values, args)
        validate_compose(target_dir)
        if not args.no_build:
            build_and_start(target_dir, args.no_start, port, env_values.get("TLS_CERT_IP", ""), env_values.get("TLS_CERT_DNS", ""))
        new_head = run_cmd(["git", "rev-parse", "HEAD"], cwd=target_dir, check=True).stdout.strip()
        state = {
            "upgraded_at": datetime.now(timezone.utc).isoformat(),
            "previous_git_head": previous_head,
            "new_git_head": new_head,
            "backup_dir": str(backup_dir),
            "health_validated": not args.no_start,
        }
        (target_dir / "upgrade_state.json").write_text(json.dumps(state, indent=2) + "\n", encoding="utf-8")
        (target_dir / "upgrade_summary.md").write_text(f"# Upgrade completado\n\n- Anterior: `{previous_head}`\n- Nuevo: `{new_head}`\n- Backup: `{backup_dir}`\n", encoding="utf-8")
        write_install_state(target_dir, args, env_values)
        log(color("Upgrade completado.", "ok"))
        return 0
    except Exception:
        warn("El upgrade no se ha validado. El backup se conserva para rollback.")
        raise


def latest_upgrade_backup(target_dir: Path) -> Path:
    root = target_dir / "upgrade_backups"
    candidates = sorted(path for path in root.glob("*") if path.is_dir()) if root.exists() else []
    if not candidates:
        raise RuntimeError("No hay backups de upgrade disponibles.")
    return candidates[-1]


def sqlite_quick_check(path: Path) -> str:
    if not path.is_file():
        raise RuntimeError(f"No existe la base SQLite: {path}")
    connection = sqlite3.connect(f"file:{path}?mode=ro", uri=True, timeout=60)
    try:
        row = connection.execute("PRAGMA quick_check").fetchone()
    finally:
        connection.close()
    result = str(row[0] if row else "")
    if result != "ok":
        raise RuntimeError(f"SQLite quick_check falló para {path}: {result}")
    return result


def validate_upgrade_backup(backup_dir: Path) -> dict[str, object]:
    manifest_path = backup_dir / "manifest.json"
    if not manifest_path.is_file():
        raise RuntimeError(f"El backup no contiene manifest.json: {backup_dir}")
    try:
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, OSError) as exc:
        raise RuntimeError(f"Manifest de backup inválido: {exc}") from exc
    if not isinstance(manifest, dict):
        raise RuntimeError("El manifest del backup no es un objeto JSON.")

    files = manifest.get("files")
    if not isinstance(files, list):
        raise RuntimeError("El manifest del backup no contiene una lista files válida.")

    backup_root = backup_dir.resolve()
    for item in files:
        if not isinstance(item, dict):
            raise RuntimeError("Entrada no válida en manifest.files.")
        relative = str(item.get("path") or "")
        if not relative:
            raise RuntimeError("Entrada de backup sin path.")
        candidate = (backup_dir / relative).resolve()
        if candidate != backup_root and backup_root not in candidate.parents:
            raise RuntimeError(f"Ruta insegura en manifest: {relative}")
        if not candidate.is_file():
            raise RuntimeError(f"Fichero ausente en backup: {relative}")
        expected_bytes = int(item.get("bytes") or -1)
        if candidate.stat().st_size != expected_bytes:
            raise RuntimeError(f"Tamaño incorrecto en backup: {relative}")
        expected_sha = str(item.get("sha256") or "")
        if not re.fullmatch(r"[0-9a-f]{64}", expected_sha):
            raise RuntimeError(f"SHA-256 inválido en manifest: {relative}")
        if sha256_file(candidate) != expected_sha:
            raise RuntimeError(f"SHA-256 no coincide en backup: {relative}")

    previous_head = str(manifest.get("previous_git_head") or "")
    if previous_head and not re.fullmatch(r"[0-9a-f]{40}", previous_head):
        raise RuntimeError("previous_git_head no es un commit SHA-1 válido.")

    backup_db = backup_dir / "data" / "auditor.db"
    if backup_db.exists():
        sqlite_quick_check(backup_db)

    log(color(f"Backup de rollback validado: {backup_dir}", "ok"))
    return manifest


def restore_sqlite_atomic(backup_db: Path, data_dir: Path) -> str:
    data_dir.mkdir(parents=True, exist_ok=True)
    target_db = data_dir / "auditor.db"
    descriptor, temporary_name = tempfile.mkstemp(
        prefix=".auditor.db.rollback-",
        suffix=".tmp",
        dir=data_dir,
    )
    os.close(descriptor)
    temporary_db = Path(temporary_name)
    try:
        shutil.copyfile(backup_db, temporary_db)
        temporary_db.chmod(0o664)
        sqlite_quick_check(temporary_db)
        for suffix in ("-wal", "-shm"):
            (data_dir / f"auditor.db{suffix}").unlink(missing_ok=True)
        os.replace(temporary_db, target_db)
        sqlite_quick_check(target_db)
        return "host_atomic"
    finally:
        temporary_db.unlink(missing_ok=True)


def compose_service_name(target_dir: Path) -> str:
    result = run_cmd(
        docker_cmd("compose", "config", "--services"),
        cwd=target_dir,
        check=True,
    )
    services = [line.strip() for line in result.stdout.splitlines() if line.strip()]
    if "auditor_ips" in services:
        return "auditor_ips"
    if len(services) == 1:
        return services[0]
    raise RuntimeError(
        "No se puede determinar de forma inequívoca el servicio de Auditor IPs."
    )


def restore_sqlite_with_docker(
    target_dir: Path,
    backup_db: Path,
    data_dir: Path,
) -> str:
    service = compose_service_name(target_dir)
    backup_mount = str(backup_db.parent.resolve())
    script = (
        "set -eu; "
        "test -f /rollback-source/auditor.db; "
        "rm -f /data/auditor.db /data/auditor.db-wal /data/auditor.db-shm; "
        "cp /rollback-source/auditor.db /data/auditor.db; "
        "chmod 0664 /data/auditor.db"
    )
    run_cmd(
        docker_cmd(
            "compose",
            "run",
            "--rm",
            "--no-deps",
            "--entrypoint",
            "/bin/sh",
            "-v",
            f"{backup_mount}:/rollback-source:ro",
            service,
            "-c",
            script,
        ),
        cwd=target_dir,
        check=True,
        capture=False,
    )
    sqlite_quick_check(data_dir / "auditor.db")
    return "docker_helper"


def restore_sqlite_database(
    target_dir: Path,
    backup_db: Path,
    data_dir: Path,
) -> str:
    try:
        method = restore_sqlite_atomic(backup_db, data_dir)
    except (OSError, PermissionError) as exc:
        warn(
            "La restauración directa no pudo sustituir la base "
            f"({exc}). Se utilizará un contenedor auxiliar."
        )
        method = restore_sqlite_with_docker(
            target_dir,
            backup_db,
            data_dir,
        )
    log(color(f"Base SQLite restaurada mediante {method}.", "ok"))
    return method


def restore_backup_files(target_dir: Path, backup_dir: Path) -> str:
    for name in (
        ".env",
        "docker-compose.yml",
        "install_state.json",
        "install_summary.md",
    ):
        source = backup_dir / name
        if source.is_file():
            shutil.copy2(source, target_dir / name)

    env_values = read_env_file(target_dir / ".env")
    data_dir = resolve_host_path(
        target_dir,
        env_values.get("DATA_DIR", "./data"),
    )
    backup_db = backup_dir / "data" / "auditor.db"
    if not backup_db.exists():
        return "no_database"
    return restore_sqlite_database(
        target_dir,
        backup_db,
        data_dir,
    )


def run_rollback(args: argparse.Namespace, target_dir: Path) -> int:
    section(
        "Rollback",
        "Restaura código, configuración y base de datos del último upgrade.",
    )
    backup_dir = latest_upgrade_backup(target_dir)
    manifest = validate_upgrade_backup(backup_dir)
    previous_head = str(manifest.get("previous_git_head") or "")
    note(f"Backup: {backup_dir}")
    note(f"Commit anterior: {previous_head}")
    if not args.yes and not confirm(
        "Detener Auditor IPs y restaurar este backup",
        False,
    ):
        return 1

    run_cmd(
        docker_cmd("compose", "down"),
        cwd=target_dir,
        check=True,
        capture=False,
    )

    # Se restaura primero la configuración y la DB. Así, un fallo de
    # permisos no modifica todavía el commit de la instalación.
    restore_method = restore_backup_files(target_dir, backup_dir)

    if previous_head:
        run_cmd(
            ["git", "checkout", args.branch],
            cwd=target_dir,
            check=True,
        )
        run_cmd(
            ["git", "reset", "--hard", previous_head],
            cwd=target_dir,
            check=True,
            capture=False,
        )

    env_values = read_env_file(target_dir / ".env")
    validate_compose(target_dir)
    build_and_start(
        target_dir,
        False,
        env_values.get("PORT", DEFAULT_PORT),
        env_values.get("TLS_CERT_IP", ""),
        env_values.get("TLS_CERT_DNS", ""),
    )
    log(color(f"Rollback completado ({restore_method}).", "ok"))
    return 0


SENSITIVE_KEY_PATTERN = re.compile(
    r"(?:password|passwd|secret|token|webhook|api[_-]?key|apikey|authorization|private[_-]?key)",
    re.IGNORECASE,
)


def is_sensitive_key(key: str) -> bool:
    return bool(SENSITIVE_KEY_PATTERN.search(str(key or "")))


def secret_values_from_env(values: dict[str, str]) -> list[str]:
    secrets_found = {
        str(value)
        for key, value in values.items()
        if is_sensitive_key(key) and str(value)
    }
    return sorted(secrets_found, key=len, reverse=True)


def redact_text(text: str, secret_values: Iterable[str] = ()) -> str:
    output = str(text or "")
    for value in sorted({str(item) for item in secret_values if str(item)}, key=len, reverse=True):
        output = output.replace(value, "[REDACTED]")

    output = re.sub(
        r"(?im)\b(authorization\s*:\s*)(?:bearer\s+)?[^\s\"']+",
        r"\1[REDACTED]",
        output,
    )
    output = re.sub(
        r"(?im)\b(password|passwd|secret|token|webhook|api[_-]?key|apikey|private[_-]?key)"
        r"(\s*[:=]\s*)([^\s,;]+)",
        r"\1\2[REDACTED]",
        output,
    )
    output = re.sub(
        r"(?i)https://(?:discord(?:app)?\.com/api/webhooks|hooks\.slack\.com/services)/[^\s\"']+",
        "[REDACTED_WEBHOOK_URL]",
        output,
    )
    return output


def redact_env(path: Path) -> str:
    if not path.exists():
        return "MISSING\n"
    output = []
    for raw in path.read_text(encoding="utf-8", errors="replace").splitlines():
        if "=" not in raw or raw.lstrip().startswith("#"):
            output.append(raw)
            continue
        key, value = raw.split("=", 1)
        if is_sensitive_key(key):
            value = "[REDACTED]" if value else ""
        output.append(f"{key}={value}")
    return "\n".join(output) + "\n"


def run_diagnose(args: argparse.Namespace, target_dir: Path) -> int:
    section("Diagnóstico", "Genera un paquete técnico redactado, sin base de datos ni secretos.")
    env_values = read_env_file(target_dir / ".env")
    secret_values = secret_values_from_env(env_values)
    diagnostics_dir = resolve_host_path(
        target_dir,
        env_values.get("DIAGNOSTICS_HOST_DIR", args.diagnostics_dir),
    )
    diagnostics_dir.mkdir(parents=True, exist_ok=True)
    stamp = datetime.now(timezone.utc).strftime("%Y%m%d-%H%M%S")
    work = Path(tempfile.mkdtemp(prefix="auditor-diagnose-"))
    try:
        (work / "system.txt").write_text(
            platform.platform()
            + "\n"
            + json.dumps(read_os_release(), indent=2)
            + "\n",
            encoding="utf-8",
        )
        (work / "env_redacted.txt").write_text(
            redact_env(target_dir / ".env"),
            encoding="utf-8",
        )
        commands = {
            "docker_version.txt": docker_cmd("version"),
            "compose_version.txt": docker_cmd("compose", "version"),
            "docker_info.txt": docker_cmd("info"),
            "compose_ps.txt": docker_cmd("compose", "ps", "-a"),
            "compose_config.txt": docker_cmd("compose", "config", "--no-interpolate"),
            "compose_logs.txt": docker_cmd("compose", "logs", "--no-color", "--tail", "300"),
            "ip_addr.txt": ["ip", "-j", "addr"],
            "ip_route.txt": ["ip", "-j", "route"],
            "disk.txt": ["df", "-h", str(target_dir)],
        }
        for filename, command in commands.items():
            result = run_cmd(command, cwd=target_dir, capture=True)
            content = (
                f"RC={result.returncode}\n"
                f"{result.stdout}\n"
                f"{result.stderr}"
            )
            (work / filename).write_text(
                redact_text(content, secret_values),
                encoding="utf-8",
            )

        port = env_values.get("PORT", DEFAULT_PORT)
        health = run_cmd(
            [
                "curl",
                "-k",
                "-sS",
                "-D",
                "-",
                "--max-time",
                "10",
                f"https://127.0.0.1:{port}/api/system/healthz",
            ],
            capture=True,
        )
        health_content = (
            f"RC={health.returncode}\n"
            f"{health.stdout}\n"
            f"{health.stderr}"
        )
        (work / "healthz.txt").write_text(
            redact_text(health_content, secret_values),
            encoding="utf-8",
        )

        leaks = []
        for path in sorted(work.rglob("*")):
            if not path.is_file():
                continue
            content = path.read_text(encoding="utf-8", errors="replace")
            for secret in secret_values:
                if secret and secret in content:
                    leaks.append(f"{path.name}:{sha256_file(path)}")
        if leaks:
            raise RuntimeError(
                "El diagnóstico contiene valores sensibles sin redactar: "
                + ", ".join(leaks)
            )

        archive = diagnostics_dir / f"auditor-ips-diagnostic-{stamp}.tar.gz"
        with tarfile.open(archive, "w:gz") as tf:
            tf.add(work, arcname="diagnostic")
        log(color(f"Diagnóstico generado y verificado: {archive}", "ok"))
        return 0
    finally:
        shutil.rmtree(work, ignore_errors=True)


def run_uninstall(args: argparse.Namespace, target_dir: Path) -> int:
    section("Desinstalación", "Puedes retirar el runtime conservando datos o realizar una eliminación completa.")
    mode = args.uninstall_mode
    if not args.yes and not args.uninstall_mode_explicit:
        mode = choose("Modo", [("runtime", "Quitar contenedor e imagen; conservar código y datos"), ("keep-data", "Quitar runtime y código; conservar datos"), ("full", "Eliminar runtime, código y datos")], 0, False)
    env_values = read_env_file(target_dir / ".env")
    data_dir = resolve_host_path(target_dir, env_values.get("DATA_DIR", "./data"))
    if not args.yes and not confirm(f"Confirmar desinstalación modo {mode}", False):
        return 1
    run_cmd(docker_cmd("compose", "down", "--remove-orphans"), cwd=target_dir, capture=False)
    if mode == "runtime":
        log(color("Runtime eliminado; código y datos conservados.", "ok"))
        return 0
    if mode == "keep-data":
        backup_target = target_dir.parent / f"{target_dir.name}-data-preserved-{datetime.now().strftime('%Y%m%d-%H%M%S')}"
        if data_dir.exists():
            shutil.move(str(data_dir), str(backup_target))
        shutil.rmtree(target_dir)
        log(color(f"Código eliminado. Datos conservados en {backup_target}", "ok"))
        return 0
    if mode == "full":
        if not args.yes:
            phrase = input("Escribe ELIMINAR TODO para confirmar: ").strip()
            if phrase != "ELIMINAR TODO":
                raise RuntimeError("Confirmación completa no recibida.")
        if data_dir.exists() and target_dir not in data_dir.parents and data_dir != target_dir:
            shutil.rmtree(data_dir)
        shutil.rmtree(target_dir)
        log(color("Instalación eliminada completamente.", "ok"))
        return 0
    raise RuntimeError(f"Modo de desinstalación no válido: {mode}")


