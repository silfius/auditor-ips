def check_path_writable(path: Path, create: bool = False) -> tuple[bool, str]:
    target = path
    if create:
        try:
            target.mkdir(parents=True, exist_ok=True)
        except OSError as exc:
            return False, str(exc)
    probe_parent = target if target.is_dir() else target.parent
    if not probe_parent.exists():
        probe_parent = next((parent for parent in probe_parent.parents if parent.exists()), Path("/"))
    try:
        fd, name = tempfile.mkstemp(prefix=".auditor-write-test-", dir=probe_parent)
        os.close(fd)
        Path(name).unlink(missing_ok=True)
        return True, str(probe_parent)
    except OSError as exc:
        return False, str(exc)


def disk_free_bytes(path: Path) -> int:
    current = path
    while not current.exists() and current != current.parent:
        current = current.parent
    return shutil.disk_usage(current).free


def clean_dns_search_domain(value: str) -> str:
    """Normaliza dominios de búsqueda y descarta raíces, rutas y valores no DNS."""
    item = str(value or "").strip()
    if item in {"", ".", "~", "~."}:
        return ""
    if item.startswith("~"):
        item = item[1:]
    item = item.strip(".")
    if not item:
        return ""
    lowered = item.lower()
    if lowered in {
        "global",
        "link",
        "default",
        "defaultroute",
        "llmnr",
        "mdns",
        "dnssec",
        "dns",
    }:
        return ""
    try:
        ipaddress.ip_address(item)
        return ""
    except ValueError:
        pass
    if not re.fullmatch(r"[A-Za-z0-9_-]+(?:\.[A-Za-z0-9_-]+)*", item):
        return ""
    if not any(ch.isalpha() for ch in item):
        return ""
    return item


def detect_resolv_conf_dns(path: Path = Path("/etc/resolv.conf")) -> dict[str, list[str]]:
    dns: list[str] = []
    search: list[str] = []
    if not path.exists():
        return {"dns": dns, "search": search}
    for raw in path.read_text(errors="replace").splitlines():
        parts = raw.strip().split()
        if not parts or parts[0].startswith("#"):
            continue
        if parts[0] == "nameserver" and len(parts) > 1:
            try:
                dns.append(str(ipaddress.ip_address(parts[1])))
            except ValueError:
                pass
        elif parts[0] in {"search", "domain"}:
            for value in parts[1:]:
                domain = clean_dns_search_domain(value)
                if domain:
                    search.append(domain)
    return {"dns": list(dict.fromkeys(dns)), "search": list(dict.fromkeys(search))}


def detect_resolvectl_dns() -> dict[str, list[str]]:
    dns: list[str] = []
    search: list[str] = []
    if not command_exists("resolvectl"):
        return {"dns": dns, "search": search}
    for command, target in ((["resolvectl", "dns"], dns), (["resolvectl", "domain"], search)):
        result = run_cmd(command, capture=True)
        if result.returncode != 0:
            continue
        for raw in result.stdout.splitlines():
            payload = raw.split(":", 1)[1] if ":" in raw else raw
            for token in re.split(r"[,\s]+", payload):
                token = token.strip()
                if not token:
                    continue
                if target is dns:
                    try:
                        target.append(str(ipaddress.ip_address(token)))
                    except ValueError:
                        pass
                else:
                    domain = clean_dns_search_domain(token)
                    if domain:
                        target.append(domain)
    return {"dns": list(dict.fromkeys(dns)), "search": list(dict.fromkeys(search))}


def detect_host_dns() -> dict[str, object]:
    dns: list[str] = []
    search: list[str] = []
    sources: list[str] = []
    for name, detector in (("resolvectl", detect_resolvectl_dns), ("/etc/resolv.conf", detect_resolv_conf_dns)):
        try:
            values = detector()
        except Exception as exc:
            warn(f"No se pudo consultar {name}: {exc}")
            continue
        if values["dns"] or values["search"]:
            sources.append(name)
        dns.extend(values["dns"])
        search.extend(values["search"])
    unique_dns = list(dict.fromkeys(dns))
    classified = []
    for value in unique_dns:
        ip = ipaddress.ip_address(value)
        if ip.is_loopback:
            kind = "loopback"
        elif ip.is_private:
            kind = "LAN/privada"
        else:
            kind = "pública"
        classified.append({"value": value, "kind": kind})
    return {"dns": classified, "search": list(dict.fromkeys(search)), "sources": sources}


def recommended_dns(detected: dict[str, object], selected_network: str) -> list[str]:
    network = ipaddress.ip_network(selected_network, strict=False)
    same_network: list[str] = []
    private: list[str] = []
    for item in detected.get("dns") or []:
        value = str(item["value"])
        ip = ipaddress.ip_address(value)
        if ip.is_loopback:
            continue
        if ip in network:
            same_network.append(value)
        elif ip.is_private:
            private.append(value)
    return same_network or private


def csv_values(values: Iterable[str]) -> str:
    return ",".join(dict.fromkeys(value.strip() for value in values if value.strip()))


def read_env_file(path: Path) -> dict[str, str]:
    values: dict[str, str] = {}
    if not path.exists():
        return values
    for raw in path.read_text(encoding="utf-8", errors="replace").splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        values[key.strip()] = value.strip().strip('"').strip("'")
    return values


def render_env(template_text: str, overrides: dict[str, str]) -> str:
    output: list[str] = []
    seen: set[str] = set()
    for line in template_text.splitlines():
        stripped = line.strip()
        if stripped and not stripped.startswith("#") and "=" in stripped:
            key = stripped.split("=", 1)[0].strip()
            if key in overrides:
                output.append(f"{key}={overrides[key]}")
                seen.add(key)
            else:
                output.append(line)
        else:
            output.append(line)
    for key, value in overrides.items():
        if key not in seen:
            output.append(f"{key}={value}")
    return "\n".join(output).rstrip() + "\n"


def render_compose(template_text: str, config: dict[str, str]) -> str:
    text = template_text
    block: list[str] = []
    for key, yaml_key in (("DOCKER_DNS", "dns"), ("DOCKER_DNS_SEARCH", "dns_search")):
        values = [value.strip() for value in config.get(key, "").split(",") if value.strip()]
        if values:
            block.append(f"    {yaml_key}:")
            block.extend(f"      - {json.dumps(value)}" for value in values)
    if block:
        marker = '    network_mode: "host"\n'
        if marker not in text:
            raise RuntimeError("La plantilla Compose no contiene network_mode: host.")
        text = text.replace(marker, marker + "\n".join(block) + "\n", 1)
    return GENERATED_COMPOSE_HEADER + text.lstrip()


def clone_or_update_repo(repo_url: str, branch: str, target_dir: Path, dry_run: bool) -> None:
    if target_dir.exists() and (target_dir / ".git").exists():
        if dry_run:
            log(f"DRY-RUN git -C {target_dir} fetch/checkout/pull {branch}")
            return
        run_cmd(["git", "fetch", "origin", branch], cwd=target_dir, check=True)
        run_cmd(["git", "checkout", branch], cwd=target_dir, check=True)
        run_cmd(["git", "pull", "--ff-only", "origin", branch], cwd=target_dir, check=True)
        return
    if target_dir.exists() and any(target_dir.iterdir()):
        markers = [target_dir / "app", target_dir / "installers" / "linux" / "env.linux.example", target_dir / "installers" / "linux" / "docker-compose.linux.yml.example"]
        if all(path.exists() for path in markers):
            note("Fuentes existentes sin .git detectadas; se utiliza la carpeta actual.")
            return
        raise RuntimeError(f"La ruta destino no está vacía ni contiene una copia válida: {target_dir}")
    if dry_run:
        log(f"DRY-RUN git clone --branch {branch} {repo_url} {target_dir}")
        return
    target_dir.parent.mkdir(parents=True, exist_ok=True)
    run_cmd(["git", "clone", "--branch", branch, repo_url, str(target_dir)], check=True)


def container_exists(name: str) -> bool:
    result = run_cmd(docker_cmd("ps", "-a", "--format", "{{.Names}}"), capture=True)
    return name in {line.strip() for line in result.stdout.splitlines()}


def perform_preflight(target_dir: Path, requested_port: str | None = None, fresh_install: bool = True) -> list[CheckResult]:
    results: list[CheckResult] = []
    os_data = read_os_release()
    results.append(CheckResult("Sistema", "OK", f"{os_data.get('PRETTY_NAME', platform.platform())} · {platform.machine()}"))
    for command in ("git", "python3", "curl", "openssl", "ip", "tar", "docker"):
        results.append(CheckResult(command, "OK" if command_exists(command) else "ERROR", shutil.which(command) or "no encontrado"))
    compose = run_cmd(docker_cmd("compose", "version"), capture=True)
    results.append(CheckResult("Docker Compose", "OK" if compose.returncode == 0 else "ERROR", (compose.stdout or compose.stderr).strip()[:160]))
    daemon = run_cmd(docker_cmd("info"), capture=True)
    results.append(CheckResult("Daemon Docker", "OK" if daemon.returncode == 0 else "ERROR", "accesible" if daemon.returncode == 0 else daemon.stderr.strip()[:160]))
    writable, detail = check_path_writable(target_dir.parent, create=False)
    results.append(CheckResult("Ruta instalación", "OK" if writable else "ERROR", detail))
    free = disk_free_bytes(target_dir)
    disk_status = "OK" if free >= RECOMMENDED_FREE_BYTES else "WARN" if free >= MIN_FREE_BYTES else "ERROR"
    results.append(CheckResult("Espacio libre", disk_status, f"{free / 1024**3:.1f} GiB"))
    interfaces = detect_ipv4_candidates(include_virtual=True)
    results.append(CheckResult("Interfaces IPv4", "OK" if interfaces else "WARN", f"{len(interfaces)} detectadas"))
    if requested_port:
        try:
            port = validate_port(requested_port)
            free_port = port_is_free(port) if fresh_install else True
            if free_port:
                results.append(CheckResult("Puerto", "OK", f"{port} libre"))
            else:
                suggested = find_free_port(port + 1)
                results.append(CheckResult("Puerto", "WARN", f"{port} ocupado; se propondrá {suggested}"))
        except RuntimeError as exc:
            results.append(CheckResult("Puerto", "ERROR", str(exc)))
    return results


