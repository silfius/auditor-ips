def main() -> int:
    args = parse_args()
    target_dir = default_target_dir(args)
    section("Auditor IPs — asistente del servidor", "Instalación guiada y explicada para Linux.")
    note(f"Repositorio: {args.repo_url}")
    note(f"Destino: {target_dir}")
    try:
        warnings = validate_platform()
        validate_commands()
        for item in warnings:
            warn(item)
        if args.diagnose:
            return run_diagnose(args, target_dir)
        if args.rollback:
            return run_rollback(args, target_dir)
        if args.uninstall:
            return run_uninstall(args, target_dir)
        if args.upgrade:
            return run_upgrade(args, target_dir)

        preflight = perform_preflight(target_dir, args.port, fresh_install=not (target_dir / ".env").exists())
        show_preflight(preflight)
        ensure_preflight_ok(preflight)
        if args.check_only:
            log(color("check-only OK", "ok"))
            return 0

        clone_or_update_repo(args.repo_url, args.branch, target_dir, args.dry_run)
        config = build_configuration(target_dir, args)
        show_effective_config_summary(target_dir, config)
        if args.dry_run:
            if not args.yes and not ask_bool("¿El resumen propuesto es correcto?", True, False, "No se escribirá ningún fichero en modo dry-run."):
                return 1
            log(color("dry-run OK: no se ha modificado el sistema.", "ok"))
            return 0
        if not args.yes and not confirm("Aplicar esta configuración", False):
            return 1
        write_local_config(target_dir, args, config)
        validate_compose(target_dir)
        do_build = not args.no_build
        do_start = not args.no_start
        if not args.yes and do_build:
            do_build = ask_bool("Construir la imagen ahora", True, False)
        if not args.yes and do_build and do_start:
            do_start = ask_bool("Arrancar y validar Auditor IPs ahora", True, False)
        if do_build:
            build_and_start(target_dir, not do_start, config["PORT"], config["TLS_CERT_IP"], config["TLS_CERT_DNS"])
        write_install_state(target_dir, args, config)
        log()
        log(color("Instalación validada correctamente.", "ok"))
        log(color(f"Abre https://{config['SERVER_IP']}:{config['PORT']}/login", "ok"))
        log("El primer administrador se crea en el asistente web inicial.")
        return 0
    except Exception as exc:
        log(color(f"ERROR: {exc}", "error"))
        return 1


